function parseRow(line) {
  const trimmed = line.trim();
  if (!trimmed) return null;

  // 1. Try standard Expiry date row (e.g. 08/27, 05/2028, etc.)
  const expMatch = trimmed.match(/\b(0[1-9]|1[0-2])[\/-](2[4-9]|3[0-9]|202[4-9]|203[0-9])\b/);
  if (expMatch) {
    const expStr = expMatch[0];
    const expIdx = trimmed.indexOf(expStr);
    const beforeExp = trimmed.substring(0, expIdx).trim();
    const afterExp = trimmed.substring(expIdx + expStr.length).trim();
    const afterTokens = afterExp.split(/\s+/).filter(Boolean);
    const numbers = afterTokens.map(t => parseFloat(t.replace(/[^0-9.]/g, ''))).filter(n => !isNaN(n));
    return { type: 'EXP_ROW', beforeExp, expStr, numbers };
  }

  // 2. Try HSN-based Sales Order / Invoice row (e.g. JJ PHARMA layout)
  // Example: 1. 200 AVAC 4'S AVABOOST BOLUS 23099090 60.00 43.00 0.00 0.00 0.00 8600.00 8600.00
  const hsnMatch = trimmed.match(/\b(2309\d{4}|3004\d{2,4}|3003\d{2,4}|3002\d{2,4}|3001\d{2,4}|88888889|\d{6,8})\b/);
  if (hsnMatch) {
    const hsn = hsnMatch[0];
    const hsnIdx = trimmed.indexOf(hsn);
    const beforeHsn = trimmed.substring(0, hsnIdx).trim();
    const afterHsn = trimmed.substring(hsnIdx + hsn.length).trim();

    const afterTokens = afterHsn.split(/\s+/).filter(Boolean);
    const numbers = afterTokens.map(t => parseFloat(t.replace(/[^0-9.]/g, ''))).filter(n => !isNaN(n));

    if (numbers.length >= 2) {
      let cleanBefore = beforeHsn.replace(/^\d+[\.\s]+/, '').trim(); // Remove leading '1.'
      let qty = 1;
      const qtyMatch = cleanBefore.match(/^(\d+)\s+(.+)$/);
      if (qtyMatch) {
        qty = parseInt(qtyMatch[1], 10);
        cleanBefore = qtyMatch[2].trim();
      }

      // Check for Manufacturer prefix
      const mfrMatch = cleanBefore.match(/^([A-Z0-9\.\-]{2,6})\s+(.+)$/);
      let mfr = '';
      if (mfrMatch && !/^(?:TAB|CAP|INJ|SYP|BOLUS|POWDER)$/i.test(mfrMatch[1])) {
        mfr = mfrMatch[1];
        cleanBefore = mfrMatch[2].trim();
      }

      // Check for Packing prefix
      let packing = '';
      const packMatch = cleanBefore.match(/^(\d+(?:\*[\w*]+|'S|\s*LTR|\s*ML|\s*GM|\s*KG|\s*GMS|\s*G|\s*MG|\s*VIAL)?|VIAL)\s+(.+)$/i);
      if (packMatch) {
        packing = packMatch[1].trim();
        cleanBefore = packMatch[2].trim();
      }

      const itemName = cleanBefore.trim();
      let mrp = numbers[0] || 0;
      let rate = numbers[1] || 0;
      let taxableValue = numbers[numbers.length - 2] || (qty * rate);
      let net = numbers[numbers.length - 1] || taxableValue;

      return {
        type: 'HSN_ROW',
        itemName,
        mfr,
        packing,
        hsn,
        qty,
        mrp,
        rate,
        taxableValue,
        net
      };
    }
  }

  return null;
}

